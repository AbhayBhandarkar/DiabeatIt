import { test, expect, navigate, snapshot, unique } from './fixtures';

test('medicine schedule → unsure intake → correction preserves occurrence and audit', async ({ page, account }) => {
  await page.goto('/');
  await navigate(page, 'Medicines');
  await page.getByRole('button', { name: 'Add medicine', exact: true }).click();
  const name = unique('Reported medicine');
  const dialog = page.getByRole('dialog', { name: 'Add reported medicine' });
  for (const [label, value] of [['Medicine name', name], ['Ingredient(s)', 'Unknown'], ['Form', 'Tablet'], ['Route', 'Oral'], ['Source / provenance', 'User-entered package note'], ['Reported instructions', 'Copy of reported instructions; no dose recommendation']]) {
    await dialog.getByLabel(label, { exact: true }).fill(value);
  }
  await dialog.getByRole('button', { name: 'Add time', exact: true }).click();
  await dialog.getByLabel('Time 1', { exact: true }).fill('00:01');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(dialog).toBeHidden();
  const card = page.getByRole('region', { name: "Today's occurrences" }).locator('article').filter({ has: page.getByRole('heading', { name, exact: true }) });
  await expect(card).toContainText('00:01 IST');
  await expect(card).toContainText('Not recorded');
  await card.getByRole('button', { name: 'Record', exact: true }).click();
  const intake = page.getByRole('dialog');
  await expect(intake.getByLabel('What happened?')).toHaveValue('unsure');
  await intake.getByLabel('Reason or context (optional)').fill('Cannot confirm whether this was taken.');
  await intake.getByRole('button', { name: 'Save record' }).click();
  await expect(intake).toBeHidden();
  await expect(card.locator('.chip').filter({ hasText: /^Unsure$/ })).toBeVisible();
  const first = await snapshot(page, account.spaceId);
  const medicine = first.entities.medicines.find(e => e.data.name === name)!;
  const original = first.entities.intakes.find(e => e.data.medicineId === medicine.id)!;
  expect(original.data.status).toBe('unsure');
  await card.getByRole('button', { name: 'Correct record' }).click();
  await intake.getByLabel('What happened?').selectOption('not-taken');
  await intake.getByLabel('Reason or context (optional)').fill('Corrected after checking the written record.');
  await intake.getByRole('button', { name: 'Save record' }).click();
  await expect(intake).toBeHidden();
  const saved = await snapshot(page, account.spaceId);
  const occurrences = saved.entities.intakes.filter(e => e.data.medicineId === medicine.id);
  expect(occurrences).toHaveLength(1);
  expect(occurrences[0]).toMatchObject({ id: original.id, version: 2, createdAt: original.createdAt, data: { date: original.data.date, scheduledTime: '00:01', status: 'not-taken' }, author: { role: 'owner' } });
  expect(saved.audit.filter(e => e.entityId === original.id).map(e => e.action).sort()).toEqual(['entity.created', 'entity.updated']);
  await page.reload();
  await navigate(page, 'Medicines');
  await page.getByRole('button', { name: 'Intake history', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Intake history' }).locator('article').filter({ hasText: name })).toContainText('Not taken');
  await page.getByRole('button', { name: 'Medicine list', exact: true }).click();
  const record = page.getByRole('region', { name: 'All medicines' }).locator('article').filter({ hasText: name });
  await expect(record.getByRole('button', { name: 'Delete', exact: true })).toBeDisabled();
  await record.getByRole('button', { name: 'Archive record' }).click();
  await expect(record).toContainText('archived');
  await page.getByRole('button', { name: 'Intake history', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Intake history' }).locator('article').filter({ hasText: name })).toContainText('Corrected after checking');
});

test('custom meal → saved recipe → portion retains unknown nutrients, not zeros', async ({ page, account }) => {
  await page.goto('/'); await navigate(page, 'Food');
  await page.getByRole('button', { name: 'Today’s meals', exact: true }).click();
  await page.getByText('Something missing?', { exact: true }).click();
  await page.getByRole('button', { name: 'Enter a food manually', exact: true }).click();
  const name = unique('Home meal');
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Food / meal name', { exact: true }).fill(name);
  await dialog.getByLabel('Portion weight (g)', { exact: true }).fill('200');
  await dialog.getByLabel('Carbohydrate (g, optional)', { exact: true }).fill('40');
  await dialog.getByLabel('Source note', { exact: true }).fill('My package transcription');
  await dialog.getByRole('button', { name: 'Log meal', exact: true }).click();
  await expect(dialog).toBeHidden();
  const card = page.locator('main article').filter({ has: page.getByRole('heading', { name, exact: true }) });
  await expect(card).toContainText('40 g');
  await expect(card.getByText('Unknown', { exact: true })).toHaveCount(3);
  await card.getByRole('button', { name: 'Save as favorite' }).click();
  const recipeName = unique('Saved recipe');
  await dialog.getByLabel('Recipe name', { exact: true }).fill(recipeName);
  await dialog.getByLabel('Number of servings in the whole recipe').fill('2');
  await dialog.getByRole('button', { name: 'Save recipe', exact: true }).click();
  await expect(dialog).toBeHidden();
  await page.getByRole('button', { name: 'Previously saved recipes', exact: true }).click();
  const recipe = page.locator('main article').filter({ has: page.getByRole('heading', { name: recipeName, exact: true }) });
  await expect(recipe).toContainText('100 g per serving');
  await expect(recipe).toContainText('20 g');
  await expect(recipe.getByText('Unknown', { exact: true })).toHaveCount(3);
  await recipe.getByRole('button', { name: 'Log portion', exact: true }).click();
  await dialog.getByLabel('Servings eaten').fill('0.5');
  await dialog.getByRole('button', { name: 'Log portion', exact: true }).click();
  await expect(dialog).toBeHidden();
  const state = await snapshot(page, account.spaceId);
  expect(state.entities.meals.find(e => e.data.name === recipeName)?.data).toMatchObject({ grams: 50, carbs: 10, fiber: null, protein: null, kcal: null });
  expect(state.entities.recipes.find(e => e.data.name === recipeName)?.data).toMatchObject({ servings: 2, ingredients: [{ grams: 200, carbs: 40, fiber: null }] });
  await page.reload(); await navigate(page, 'Food');
  await page.getByRole('button', { name: 'Today’s meals', exact: true }).click();
  await expect(page.locator('main article').filter({ has: page.getByRole('heading', { name: recipeName, exact: true }) })).toContainText('10 g');
});