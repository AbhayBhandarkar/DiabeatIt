import { test, expect, navigate, snapshot } from './fixtures';
import { videoLessons } from '../../shared/videoLessons';

for (const lesson of videoLessons) test(`actual MP4 checkpoint 31, seek protection and transcript completion: ${lesson.id}`, async ({ page, account }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/'); await navigate(page, 'Learn');
  await page.getByRole('button', { name: `Explore lesson: ${lesson.title}`, exact: true }).click();
  const dialog = page.getByRole('dialog', { name: lesson.title, exact: true });
  const video = dialog.locator('video');
  await expect(video).toHaveAttribute('src', lesson.video.src);
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.readyState)).toBeGreaterThanOrEqual(2);
  expect(await video.evaluate((v: HTMLVideoElement) => v.duration)).toBeCloseTo(48, 0);
  expect(await video.evaluate((v: HTMLVideoElement) => v.paused)).toBe(true);
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.textTracks[0]?.mode)).toBe('showing');
  await expect(dialog.getByRole('button', { name: 'Mark lesson complete' })).toBeDisabled();
  // Native media playback, not synthetic timeupdate/ended events.
  await video.evaluate(async (v: HTMLVideoElement) => { await v.play(); });
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeGreaterThan(0);
  await video.evaluate((v: HTMLVideoElement) => { v.currentTime = 40; });
  const checkpoint = lesson.checkpoints[0];
  await expect(dialog.getByRole('heading', { name: checkpoint.prompt, exact: true })).toBeVisible();
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeCloseTo(31, 1);
  expect(await video.evaluate((v: HTMLVideoElement) => v.paused)).toBe(true);
  await expect(dialog.getByRole('button', { name: 'Continue after checkpoint' })).toBeDisabled();
  const wrong = checkpoint.choices.find(c => c.id !== checkpoint.correctChoiceId)!;
  await dialog.getByRole('button', { name: wrong.text, exact: true }).click();
  await expect(dialog.getByText(`Not quite. ${wrong.feedback}`, { exact: true })).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Continue after checkpoint' })).toBeDisabled();
  const correct = checkpoint.choices.find(c => c.id === checkpoint.correctChoiceId)!;
  await dialog.getByRole('button', { name: correct.text, exact: true }).click();
  await dialog.getByRole('button', { name: 'Continue after checkpoint' }).click();
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime)).toBeCloseTo(32, 1);
  await video.evaluate(async (v: HTMLVideoElement) => { v.currentTime = v.duration - 0.2; await v.play(); });
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.ended)).toBe(true);
  await expect(dialog.getByRole('button', { name: 'Mark lesson complete' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Save progress', exact: true }).click();
  await expect(dialog.getByText(/Resume position .* saved\./)).toBeVisible();
  expect((await snapshot(page, account.spaceId)).entities.lessons.find(e => e.data.lessonId === lesson.id)?.data.completed).toBe(false);
  await dialog.getByRole('button', { name: 'Use accessible transcript' }).click();
  const transcript = await page.request.get(lesson.transcript);
  expect(transcript.status()).toBe(200);
  const fullTranscript = await transcript.text();
  expect(fullTranscript.length).toBeGreaterThan(300);
  await expect(dialog.getByRole('region', { name: 'Lesson transcript' })).toHaveText(fullTranscript);
  await expect(dialog.getByRole('button', { name: 'Mark lesson complete' })).toBeDisabled();
  await dialog.getByRole('checkbox', { name: 'I have read the full transcript and explanations.' }).check();
  await dialog.getByRole('button', { name: 'Mark lesson complete' }).click();
  await expect(dialog.getByText('Lesson completion saved.', { exact: true })).toBeVisible();
  const saved = (await snapshot(page, account.spaceId)).entities.lessons.filter(e => e.data.lessonId === lesson.id);
  expect(saved).toHaveLength(1); expect(saved[0].data.completed).toBe(true);
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await page.reload(); await navigate(page, 'Learn');
  await expect(page.locator('.video-card').filter({ has: page.getByRole('heading', { name: lesson.title, exact: true }) })).toContainText('Completion saved');
  expect(errors).toEqual([]);
});